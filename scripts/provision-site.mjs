#!/usr/bin/env node
import { chmodSync, existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const valueFor = (flag) => {
  const index = args.indexOf(flag);
  return index >= 0 ? args[index + 1] : '';
};
const has = (flag) => args.includes(flag);
const manifestArg = valueFor('--manifest');
const outputArg = valueFor('--env') || '.env';
const force = has('--force');
const checkOnly = has('--check');

function stop(message) {
  console.error(`Provisioning failed: ${message}`);
  process.exit(1);
}

if (!manifestArg) {
  stop('pass --manifest <site-manifest.json>. Start from site.manifest.example.json.');
}

const manifestPath = resolve(process.cwd(), manifestArg);
if (!existsSync(manifestPath)) stop(`manifest not found: ${manifestArg}`);
let site;
try {
  site = JSON.parse(readFileSync(manifestPath, 'utf8'));
} catch (error) {
  stop(`manifest is not valid JSON (${error instanceof Error ? error.message : String(error)}).`);
}

const required = [
  'mode', 'siteName', 'siteOwner', 'siteDescription', 'siteUrl', 'deployAdapter',
  'tinaClientId', 'tinaToken', 'tinaBranch', 'githubContentRepo',
  'cloudinaryCloudName', 'cloudinaryApiKey', 'cloudinaryApiSecret', 'cloudinaryRootFolder',
];
const missing = required.filter((key) => !String(site[key] ?? '').trim());
if (missing.length) stop(`missing required manifest keys: ${missing.join(', ')}.`);
if (!['independent', 'same-site-migration'].includes(site.mode)) stop('mode must be "independent" or "same-site-migration".');
if (!['node', 'vercel', 'cloudflare', 'netlify'].includes(site.deployAdapter)) stop('deployAdapter must be node, vercel, cloudflare, or netlify.');
site.siteUrl = String(site.siteUrl).trim();
let parsedSiteUrl;
try {
  parsedSiteUrl = new URL(site.siteUrl);
} catch {
  stop('siteUrl must be a valid HTTPS origin without credentials, path, query, or fragment.');
}
if (parsedSiteUrl.protocol !== 'https:' || parsedSiteUrl.origin !== site.siteUrl || parsedSiteUrl.username || parsedSiteUrl.password) {
  stop('siteUrl must be a valid HTTPS origin without credentials, path, query, or fragment.');
}
if (!/^[^/\s]+\/[^/\s]+$/.test(site.githubContentRepo)) stop('githubContentRepo must use owner/repository format.');
if (!/^[A-Za-z0-9._-]+$/.test(site.cloudinaryRootFolder)) stop('cloudinaryRootFolder may contain only letters, numbers, dot, underscore, and dash.');
if (site.formspreeEndpoint && !/^https:\/\/formspree\.io\/f\/[A-Za-z0-9_-]+$/.test(site.formspreeEndpoint)) stop('formspreeEndpoint is malformed.');

const values = Object.values(site).map((value) => String(value ?? '').toLowerCase());
if (values.some((value) => /replace-with|example\.com|your[_-]|placeholder/.test(value))) {
  stop('replace every placeholder value before provisioning.');
}

if (site.mode === 'independent') {
  const forbidden = [
    ['siteUrl', /boilerplate\.blissdrive\.net/i],
    ['tinaClientId', /^40bc8cd1-d0fe-4061-b99c-d91be2de59e0$/i],
    ['githubContentRepo', /^bliss-tinacms\/boilerplate$/i],
    ['cloudinaryRootFolder', /^(boilerplate|starter|default)$/i],
  ];
  for (const [key, pattern] of forbidden) {
    if (pattern.test(String(site[key]))) stop(`${key} reuses the source boilerplate identity; create an isolated value for this site.`);
  }
}

const contentApiUrl = String(site.tinaContentApiUrl || `${site.siteUrl}/tina-content-proxy`);
if (contentApiUrl !== `${site.siteUrl}/tina-content-proxy`) stop('tinaContentApiUrl must use this site origin and /tina-content-proxy.');

const envLines = [
  '# Generated by pnpm site:provision. Do not commit this file.',
  `SITE_PROVISION_MODE=${site.mode}`,
  `SITE_URL=${site.siteUrl}`,
  `DEPLOY_ADAPTER=${site.deployAdapter}`,
  `NEXT_PUBLIC_TINA_CLIENT_ID=${site.tinaClientId}`,
  `TINA_TOKEN=${site.tinaToken}`,
  `NEXT_PUBLIC_TINA_BRANCH=${site.tinaBranch}`,
  `GITHUB_CONTENT_REPO=${site.githubContentRepo}`,
  `CLOUDINARY_CLOUD_NAME=${site.cloudinaryCloudName}`,
  `CLOUDINARY_API_KEY=${site.cloudinaryApiKey}`,
  `CLOUDINARY_API_SECRET=${site.cloudinaryApiSecret}`,
  `CLOUDINARY_ROOT_FOLDER=${site.cloudinaryRootFolder}`,
  `NEXT_PUBLIC_TINA_CONTENT_API_URL=${contentApiUrl}`,
  '',
];
if (envLines.some((line) => /[\r\n]/.test(line))) stop('manifest values must not contain newlines.');

const envPath = resolve(root, outputArg);
if (existsSync(envPath) && !force && !checkOnly) stop(`${basename(envPath)} already exists; inspect it and rerun with --force only when replacement is intentional.`);

const configPath = join(root, 'src/content/config/config.json');
const config = JSON.parse(readFileSync(configPath, 'utf8'));
config.seo = {
  ...(config.seo || {}),
  title: site.siteName,
  description: site.siteDescription,
  siteOwner: site.siteOwner,
};
if (site.formspreeEndpoint) {
  config.contactForm = { ...(config.contactForm || {}), formspreeEndpoint: site.formspreeEndpoint };
}

if (checkOnly) {
  console.log(`Provisioning manifest passed (${site.mode}); no files written.`);
  process.exit(0);
}

const temporaryEnv = `${envPath}.tmp-${process.pid}`;
writeFileSync(temporaryEnv, envLines.join('\n'), { mode: 0o600 });
renameSync(temporaryEnv, envPath);
chmodSync(envPath, 0o600);
writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`);
console.log(`Provisioned ${site.mode} runtime at ${outputArg}; updated neutral site identity in src/content/config/config.json.`);
console.log('Next: pnpm validate:site && pnpm build:local. Push the Tina branch before pnpm build. Keep the generated environment file untracked.');
